
import streamlit as st
import json
from datetime import datetime

st.set_page_config(
    page_title="CyberTalk",
    page_icon="🤝",
    layout="wide"
)

st.title("🤖 CyberTalk: Two Chatbots, One Agreement")
st.write(
    "Two AI personas discuss a topic, explore different views, "
    "and work toward a shared agreement."
)

st.info("Demo Mode is available without an API key.")

topic = st.text_input(
    "Enter a discussion topic",
    "How can we improve cybersecurity?"
)

persona_a = st.selectbox(
    "Chatbot 1",
    ["Security Expert", "Student", "Business Owner", "Researcher"]
)

persona_b = st.selectbox(
    "Chatbot 2",
    ["Privacy Advocate", "Teacher", "Developer", "Researcher"]
)

rounds = st.slider("Number of discussion rounds", 1, 5, 3)

if st.button("Start Conversation", type="primary"):
    if not topic.strip():
        st.warning("Please enter a topic.")
    else:
        conversation = []

        responses_a = [
            f"As a {persona_a}, I believe we should identify the main risks related to {topic}.",
            "We should use practical safeguards, clear rules, and regular reviews.",
            "I agree that the solution should be effective, affordable, and easy to maintain.",
            "We should also assign responsibilities and review progress regularly.",
            "A balanced approach can help us achieve our shared goal."
        ]

        responses_b = [
            f"As a {persona_b}, I think we should also consider people's needs regarding {topic}.",
            "Transparency, fairness, and protecting people's interests are important.",
            "The solution should be understandable and should avoid unnecessary restrictions.",
            "We should collect feedback and improve the approach over time.",
            "I support a solution that balances safety with practical needs."
        ]

        st.subheader("Discussion")

        for i in range(rounds):
            st.markdown(f"**Round {i + 1} — {persona_a}**")
            st.write(responses_a[i])
            conversation.append({
                "round": i + 1,
                "speaker": persona_a,
                "message": responses_a[i]
            })

            st.markdown(f"**Round {i + 1} — {persona_b}**")
            st.write(responses_b[i])
            conversation.append({
                "round": i + 1,
                "speaker": persona_b,
                "message": responses_b[i]
            })

        st.subheader("🤝 Shared Agreement")

        agreement = (
            f"Both participants agree to address '{topic}' through a "
            "balanced, transparent, and practical approach. They will "
            "consider safety, privacy, fairness, and the needs of affected "
            "people. They will review the results and make improvements "
            "when necessary."
        )

        st.success(agreement)

        result = {
            "project": "CyberTalk",
            "topic": topic,
            "mode": "Demo",
            "generated_at": datetime.now().isoformat(timespec="seconds"),
            "agreement": agreement,
            "conversation": conversation
        }

        st.download_button(
            "Download Transcript (JSON)",
            data=json.dumps(result, indent=2),
            file_name="cybertalk_transcript.json",
            mime="application/json"
        )

        transcript = f"CyberTalk Discussion\nTopic: {topic}\n\n"
        for item in conversation:
            transcript += (
                f"Round {item['round']} - {item['speaker']}:\n"
                f"{item['message']}\n\n"
            )
        transcript += f"Shared Agreement:\n{agreement}\n"

        st.download_button(
            "Download Transcript (TXT)",
            data=transcript,
            file_name="cybertalk_transcript.txt",
            mime="text/plain"
        )

st.caption(
    "CyberTalk prototype | Demo responses are predefined, "
    "not generated by a live AI model."
)
